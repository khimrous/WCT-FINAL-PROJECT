/**
 * Safely resolves nested keys with English fallback
 * @param {string} path - Key path (e.g., 'recipe.addToCart')
 * @param {string} lang - Selected language code ('en' | 'km')
 * @returns {string} Translated string or key fallback
 */
export function getTranslation(path, lang = 'en') {
  const keys = path.split('.')
  
  const resolve = (locale) => {
    return keys.reduce((acc, curr) => (acc && acc[curr] !== undefined ? acc[curr] : null), translations[locale])
  }

  return resolve(lang) || resolve('en') || path
}